const { test } = require('node:test');
const assert = require('node:assert/strict');
const { readFile } = require('node:fs/promises');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');
const load = require('./helpers/load-source.cjs');
const { PostgresWatchRepository } = load(path.resolve(__dirname, '../src/infrastructure/repositories/PostgresWatchRepository.ts'));
const express = require('express');
const { createWishlistRoutes } = load(path.resolve(__dirname, '../src/presentation/routes/wishlistRoutes.ts'));
const { createStockAlertRoutes } = load(path.resolve(__dirname, '../src/presentation/routes/stockAlertRoutes.ts'));
const { errorHandler } = load(path.resolve(__dirname, '../src/presentation/middleware.ts'));
test('catalog persistence: stock alerts enqueue once, variant ownership is protected, wishlist is per account', async t => {
  const pg = new PGlite();
  for (const file of ['schema.sql', 'features/01-catalog.sql', 'features/02-commerce.sql', 'features/03-content.sql']) await pg.exec(await readFile(path.resolve(__dirname, '../src/infrastructure/database', file), 'utf8'));
  const adapt = executor => async (sql, params = []) => { const result = await executor.query(sql, params); return { ...result, rowCount: result.affectedRows ?? result.rows.length }; };
  const db = { query: adapt(pg), transaction: work => pg.transaction(client => work({ query: adapt(client) })) };
  const user = (await db.query("INSERT INTO users(mobile) VALUES('09121111111') RETURNING *")).rows[0];
  const other = (await db.query("INSERT INTO users(mobile) VALUES('09122222222') RETURNING *")).rows[0];
  const auth = { authenticate: async token => token === 'other' ? other : user };
  const repository = new PostgresWatchRepository(db);
  const watch = await repository.create({ name: 'Stock Test', description: 'A product for stock alerts', price: 500000, imageUrl: '/watch.svg', category: 'original', stockQuantity: 0 });
  const app = express(); app.use(express.json()); app.use('/wishlist', createWishlistRoutes(auth, db)); app.use('/alerts', createStockAlertRoutes(auth, db)); app.use(errorHandler);
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await pg.close(); });
  const api = async (url, method, body, token = 'user') => {
    const response = await fetch('http://127.0.0.1:' + server.address().port + url, { method, headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + token }, ...(body ? { body: JSON.stringify(body) } : {}) });
    return { status: response.status, data: await response.json() };
  };
  assert.equal((await api('/alerts', 'POST', { watchId: watch.id })).status, 201);
  assert.equal((await api('/alerts', 'POST', { watchId: watch.id })).status, 201);
  assert.equal((await db.query('SELECT * FROM stock_alerts')).rows.length, 1);
  await repository.update(watch.id, { stockQuantity: 3 });
  assert.equal((await db.query("SELECT * FROM notification_outbox WHERE kind='restock_sms'")).rows.length, 1);
  await repository.update(watch.id, { stockQuantity: 4 });
  assert.equal((await db.query("SELECT * FROM notification_outbox WHERE kind='restock_sms'")).rows.length, 1);
  assert.equal((await api('/alerts', 'POST', { watchId: watch.id })).status, 409);
  assert.equal((await api('/wishlist', 'PUT', { watchIds: [watch.id] })).status, 200);
  assert.deepEqual((await api('/wishlist', 'GET')).data.watchIds, [watch.id]);
  assert.deepEqual((await api('/wishlist', 'GET', undefined, 'other')).data.watchIds, []);
  const stale = await api('/wishlist', 'PUT', { watchIds: [watch.id, '00000000-0000-4000-8000-000000000001'] });
  assert.equal(stale.status, 200);
  assert.deepEqual(stale.data.watchIds, [watch.id]);
  const variantId = 'acf10e1c-1ee8-4666-a278-de715bd34edf';
  const variants = [{ id: variantId, sku: 'BLACK-TEST', label: 'Black', price: 500000, stockQuantity: 0 }];
  await repository.update(watch.id, { variants });
  assert.equal((await api('/alerts', 'POST', { watchId: watch.id, variantId })).status, 201);
  await repository.update(watch.id, { variants: [{ ...variants[0], stockQuantity: 2 }] });
  assert.equal((await db.query("SELECT * FROM notification_outbox WHERE kind='restock_sms'")).rows.length, 2);
  const second = await repository.create({ name: 'Second', description: 'Another product', price: 500000, imageUrl: '/watch.svg', category: 'original' });
  await assert.rejects(repository.update(second.id, { variants }), error => error.status === 400 || error.status === 409);
  assert.equal((await repository.findById(watch.id)).variants[0].stockQuantity, 2);
});
